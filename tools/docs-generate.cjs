#!/usr/bin/env node
/**
 * Auto-generates scripts/readme.md (Windows index), scripts-linux/readme.md
 * (Linux/macOS index), and docs/parity-matrix.md (cross-OS coverage),
 * sourced from registry.yaml + per-script manifest.json files.
 *
 * Run via `node tools/docs-generate.cjs`. Use `--check` in CI to fail on drift.
 */
const fs = require("fs");
const path = require("path");
const yaml = require("js-yaml");

const ROOT = path.resolve(__dirname, "..");
const REG  = path.join(ROOT, "registry.yaml");
const MARK = "<!-- AUTO-GENERATED by tools/docs-generate.cjs -- DO NOT EDIT BY HAND -->";

const doc = yaml.load(fs.readFileSync(REG, "utf8"));

function readManifest(plat, folder) {
  const base = plat === "windows" ? "scripts" : "scripts-linux";
  const p = path.join(ROOT, base, folder, "manifest.json");
  if (!fs.existsSync(p)) return null;
  try { return JSON.parse(fs.readFileSync(p, "utf8")); } catch { return null; }
}

function rows(plat) {
  const out = [];
  for (const s of doc.scripts) {
    const block = s[plat];
    if (!block) continue;
    const m = readManifest(plat, block.folder) || {};
    out.push({
      id: s.id,
      folder: block.folder,
      title: block.title || m.summary || m.name || block.folder,
      phase: block.phase || m.phase || "",
      destructive: m.destructive ? "yes" : "",
      aliases: (m.aliases || []).join(", "),
    });
  }
  return out;
}

function table(headers, data) {
  const head = `| ${headers.join(" | ")} |`;
  const sep  = `| ${headers.map(() => "---").join(" | ")} |`;
  const body = data.map((r) => `| ${headers.map((h) => r[h.toLowerCase()] || "").join(" | ")} |`).join("\n");
  return `${head}\n${sep}\n${body}`;
}

function buildWindows() {
  const data = rows("windows");
  return [
    MARK,
    `# Windows Scripts Index`,
    "",
    `Auto-generated from \`registry.yaml\` + each script's \`manifest.json\`. **${data.length}** scripts.`,
    "",
    `Run: \`.\\run.ps1 -I <id>\` or \`.\\run.ps1 install <alias>\`.`,
    "",
    table(["ID", "Folder", "Title", "Phase", "Aliases", "Destructive"], data),
    "",
    `_Edit \`registry.yaml\` or the relevant \`manifest.json\`, then run \`node tools/docs-generate.cjs\`._`,
    "",
  ].join("\n");
}

function buildLinux() {
  const data = rows("linux");
  return [
    MARK,
    `# Linux / macOS Scripts Index`,
    "",
    `Auto-generated. **${data.length}** scripts. Run: \`bash scripts-linux/run.sh <verb> -I <id>\`.`,
    "",
    table(["ID", "Folder", "Title", "Phase", "Aliases", "Destructive"], data),
    "",
  ].join("\n");
}

function buildParity() {
  const lines = [MARK, `# Cross-OS Parity Matrix`, "",
    `Auto-generated from \`registry.yaml\`. Legend: ✅ supported, ⬜ not implemented.`, "",
    `| ID | Title | Windows | Linux | macOS |`,
    `| --- | --- | :---: | :---: | :---: |`];
  let wOnly = 0, lOnly = 0, all = 0;
  for (const s of doc.scripts) {
    const w = s.windows ? "✅" : "⬜";
    const l = s.linux   ? "✅" : "⬜";
    const m = s.macos   ? "✅" : "⬜";
    if (s.windows && !s.linux) wOnly++;
    if (s.linux && !s.windows) lOnly++;
    if (s.windows && s.linux && s.macos) all++;
    const title = (s.windows && s.windows.folder) || (s.linux && s.linux.title) || s.id;
    lines.push(`| ${s.id} | ${title} | ${w} | ${l} | ${m} |`);
  }
  lines.push("", `**Coverage:** ${all} on all three OSes · ${wOnly} Windows-only · ${lOnly} Linux/macOS-only · ${doc.scripts.length} total.`, "");
  return lines.join("\n");
}

const artefacts = [
  { path: "scripts/readme.md",      body: buildWindows() },
  { path: "scripts-linux/readme.md", body: buildLinux() },
  { path: "docs/parity-matrix.md",  body: buildParity() },
];

const check = process.argv.includes("--check");
let drift = 0, wrote = 0;
for (const a of artefacts) {
  const abs = path.join(ROOT, a.path);
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  const cur = fs.existsSync(abs) ? fs.readFileSync(abs, "utf8") : "";
  if (cur.trim() === a.body.trim()) { console.log(`[OK] ${a.path} up-to-date`); continue; }
  if (check) { console.error(`[DRIFT] ${a.path}`); drift++; }
  else { fs.writeFileSync(abs, a.body); console.log(`[OK] wrote ${a.path}`); wrote++; }
}
if (check && drift) { console.error("Run: node tools/docs-generate.cjs"); process.exit(1); }
console.log(`[OK] docs generation done (${wrote} written, ${drift} drift)`);
